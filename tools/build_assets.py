"""Turn the art in art/png into everything the Z80 needs.

    python3 tools/build_assets.py

Writes into build/:
  tables.asm    line offsets, Mode 0 pen bits, rainbow
  palettes.asm  raster tables (palette + mode per interrupt zone)
  sprites.asm   masked sprites + one sprite-set table per episode
  BG1/BG2/BG3   16K screen images for banks #C4-#C6
  GFX7          bank #C7: the packed menu picture
  c7.asm        where things are inside GFX7
  SLOPSCR       the loading screen (raw 16K, loaded at #C000)
  loader.bas    the BASIC loader (with the loading-screen inks)

A missing PNG falls back to a generated placeholder, so the game always
builds; tools/placeholders.py documents the expected sizes.
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import cpcgfx as G          # noqa: E402
import placeholders as P    # noqa: E402

ART = os.path.join(ROOT, "art", "png")
BUILD = os.path.join(ROOT, "build")


def art(name):
    p = os.path.join(ART, name + ".png")
    if os.path.exists(p):
        return Image.open(p).convert("RGBA"), True
    return P.make(name), False


# ---------------------------------------------------------------- sprites
# name -> (mode, palette, frame width px, frame height, frames)
SPRITES = {
    "themis_m1": (1, "ep1", 24, 24, 5),
    "robot_m1":  (1, "ep1", 32, 20, 2),
    "items_ep1": (1, "ep1", 16, 16, 6),
    "items_ep2": (1, "ep2", 16, 16, 6),
    "power_m1":  (1, "ep1", 16, 16, 2),
    "poof_m1":   (1, "ep1", 16, 16, 3),
    "bolt_m1":   (1, "ep1", 8, 10, 1),
    "themis_m0": (0, "ep3", 12, 24, 5),
    "robot_m0":  (0, "ep3", 16, 20, 2),
    "items_ep3": (0, "ep3", 12, 16, 6),
    "power_m0":  (0, "ep3", 12, 16, 2),
    "poof_m0":   (0, "ep3", 12, 16, 3),
    "bolt_m0":   (0, "ep3", 4, 10, 1),
    "bro_float": (0, "ep3", 12, 32, 1),
    "bro_walk":  (0, "ep3", 12, 24, 2),
}

# sprite sets: SS_PLAYER(5) SS_ROBOT(2) SS_ITEMS(6) SS_POWER(2) SS_POOF(3) SS_BOLT(1) SS_BRO(3)
SETS = {
    "spr_set_ep1": ["themis_m1"] * 5 + ["robot_m1"] * 2 + ["items_ep1"] * 6 + ["power_m1"] * 2
                   + ["poof_m1"] * 3 + ["bolt_m1"] + ["bro_float"] + ["bro_walk"] * 2,
}


def build_sprites():
    out = ["; generated by tools/build_assets.py - do not edit"]
    labels = {}
    used_art = []
    for name, (mode, pal, fw, fh, n) in SPRITES.items():
        img, real = art(name)
        if real:
            used_art.append(name)
        assert img.size == (fw * n, fh), (name, img.size, (fw * n, fh))
        palrgb = G.pal_rgb(pal)
        labels[name] = []
        for f in range(n):
            fr = img.crop((f * fw, 0, f * fw + fw, fh))
            data = G.sprite_bytes(fr, palrgb, mode)
            lab = "spr_%s_%d" % (name, f)
            labels[name].append(lab)
            out.append(lab + ":")
            out.append(G.db_lines(data))

    def set_table(lab, player, robot, items, power, poof, bolt):
        refs = labels[player] + labels[robot] + labels[items] + labels[power] + labels[poof] \
            + labels[bolt] + labels["bro_float"] + labels["bro_walk"]
        assert len(refs) == 22
        out.append(lab + ":")
        out.append("    dw " + ",".join(refs))

    set_table("spr_set_ep1", "themis_m1", "robot_m1", "items_ep1", "power_m1", "poof_m1", "bolt_m1")
    set_table("spr_set_ep2", "themis_m1", "robot_m1", "items_ep2", "power_m1", "poof_m1", "bolt_m1")
    set_table("spr_set_ep3", "themis_m0", "robot_m0", "items_ep3", "power_m0", "poof_m0", "bolt_m0")
    write("sprites.asm", "\n".join(out) + "\n")
    print("sprites: real art for %s" % (", ".join(used_art) or "nothing yet"))


# ---------------------------------------------------------------- tables
def build_tables():
    out = ["; generated by tools/build_assets.py - do not edit", "line_tab:"]
    offs = [G.line_offset(y) for y in range(200)]
    for i in range(0, 200, 10):
        out.append("    dw " + ",".join("#%04X" % o for o in offs[i:i + 10]))
    out.append("m0_left:")
    out.append("    db " + ",".join("#%02X" % G.m0_byte(p, 0) for p in range(16)))
    wheel = [6, 15, 24, 18, 20, 11, 2, 5, 8, 7]
    out.append("rainbow:")
    out.append("    db " + ",".join("#%02X" % G.ga_colour(c) for c in wheel))
    write("tables.asm", "\n".join(out) + "\n")


def zone(label, mode, pal, n=None):
    cols = G.PAL[pal] if isinstance(pal, str) else pal
    if n is not None:
        cols = cols[:n]
    m = {None: 0, 0: 0x8C, 1: 0x8D}[mode]
    return "%s: db #%02X,%d,%s" % (label, m, len(cols), ",".join("#%02X" % G.ga_colour(c) for c in cols))


def build_palettes():
    out = ["; generated by tools/build_assets.py - do not edit"]
    out.append("rast_black: dw 0,rz_black,0,0,0,0")
    out.append(zone("rz_black", None, [0] * 16))
    for ep in (1, 2):
        out.append("rast_ep%d: dw 0,rz_hud%d,rz_pf%d,0,0,rz_shelf%d" % (ep, ep, ep, ep))
        out.append(zone("rz_hud%d" % ep, 1, "hud%d" % ep))
        out.append(zone("rz_pf%d" % ep, 1, "ep%d" % ep))
        out.append(zone("rz_shelf%d" % ep, None, "shelf%d" % ep))
    out.append("rast_ep3: dw 0,rz_hud3,rz_pf3,0,0,0")
    out.append(zone("rz_hud3", 1, "hud3"))
    out.append(zone("rz_pf3", 0, "ep3"))
    out.append("rast_menu: dw 0,rz_menu1,rz_menu2,rz_menu3,rz_menu4,rz_menu5")
    out.append(zone("rz_menu1", 0, "menu"))
    for z in range(2, 6):
        out.append(zone("rz_menu%d" % z, None, "menu", 4))
    write("palettes.asm", "\n".join(out) + "\n")


# ---------------------------------------------------------- full screens
def pens_of(img, pal):
    """indexed image -> its indices; RGB -> nearest pens of `pal`."""
    if img.mode == "P":
        w, h = img.size
        px = img.load()
        return [[px[x, y] for x in range(w)] for y in range(h)]
    pens, _ = G.image_pens(img.convert("RGBA"), G.pal_rgb(pal), alpha=False)
    return pens


def load_screen(name, fallback):
    p = os.path.join(ART, name + ".png")
    if os.path.exists(p):
        img = Image.open(p)
        if img.mode not in ("P",):
            img = img.convert("RGB")
        return img, True
    return fallback(), False


def halve(rows):
    return [r[0::2] for r in rows]


def build_background(ep):
    """320x200 picture: lines 0-31 HUD (Mode 1), 32-39 blank, 40-189 the
    playfield (Mode 1, or Mode 0 for episode 3), 190-199 shelf."""
    img, real = load_screen("bg%d" % ep, lambda: P.background(ep))
    assert img.size in ((320, 200), (160, 200)), img.size
    if img.mode == "P" and img.size == (160, 200):
        rows = pens_of(img, "ep3")
        full = [[p for p in r for _ in (0, 1)] for r in rows]
    else:
        full = None
    rgb = img.convert("RGB")
    if rgb.size == (160, 200):
        rgb = rgb.resize((320, 200), Image.NEAREST)
    hud = pens_of(rgb.crop((0, 0, 320, 32)), "hud%d" % ep)
    blank = [[0] * 320 for _ in range(8)]
    if ep == 3:
        if full is not None:
            pf = halve([r for r in full[40:190]])
        else:
            pf = pens_of(rgb.crop((0, 40, 320, 190)).resize((160, 150), Image.NEAREST), "ep3")
        shelf = pens_of(rgb.crop((0, 190, 320, 200)).resize((160, 10), Image.NEAREST), "ep3")
        bands = [(0, 32, 1, hud), (32, 40, 1, blank), (40, 190, 0, pf), (190, 200, 0, shelf)]
    else:
        pf = pens_of(rgb.crop((0, 40, 320, 190)), "ep%d" % ep)
        shelf = pens_of(rgb.crop((0, 190, 320, 200)), "shelf%d" % ep)
        bands = [(0, 32, 1, hud), (32, 40, 1, blank), (40, 190, 1, pf), (190, 200, 1, shelf)]
    scr = G.screen_from_bands(bands)
    write("BG%d" % ep, scr, binary=True)
    preview(bands, "bg%d_preview.png" % ep, ep)
    return real


def preview(bands, name, ep):
    """What the CPC will show, as a PNG (for reviewing the art)."""
    pals = {}
    if ep == 3:
        pal_pf = G.pal_rgb("ep3")
        pal_shelf = G.pal_rgb("ep3")
    elif ep in (1, 2):
        pal_pf = G.pal_rgb("ep%d" % ep)
        pal_shelf = G.pal_rgb("shelf%d" % ep)
    else:
        pal_pf = pal_shelf = G.pal_rgb(ep)
    img = Image.new("RGB", (320, 200))
    for y0, y1, mode, rows in bands:
        if ep in (1, 2, 3):
            pal = G.pal_rgb("hud%d" % ep) if y0 == 0 else (pal_shelf if y0 == 190 else pal_pf)
        else:
            pal = pal_pf
        for y in range(y0, y1):
            r = rows[y - y0]
            sx = 320 // len(r)
            for x, p in enumerate(r):
                for k in range(sx):
                    img.putpixel((x * sx + k, y), pal[p])
    img.resize((640, 400), Image.NEAREST).save(os.path.join(BUILD, name))


def build_fullscreen_m0(name, pal, fallback):
    img, real = load_screen(name, fallback)
    if img.size == (320, 200):
        img = img.resize((160, 200), Image.NEAREST)
    assert img.size == (160, 200), (name, img.size)
    rows = pens_of(img, pal)
    bands = [(0, 200, 0, rows)]
    preview(bands, name + "_preview.png", pal)
    return G.screen_from_bands(bands), real


def build_menu_and_c7():
    scr, real = build_fullscreen_m0("menu", "menu", P.menu)
    packed = G.lz_pack(scr)
    assert G.lz_unpack(packed) == scr
    assert len(packed) <= 0x4000, len(packed)
    write("GFX7", packed, binary=True)
    write("c7.asm", "; generated - contents of bank #C7\nc7_menu equ #4000\n")
    print("menu: %d bytes packed (%s)" % (len(packed), "art" if real else "placeholder"))


def build_loader():
    scr, real = build_fullscreen_m0("loader", "loader", P.loader)
    write("SLOPSCR", scr, binary=True)
    inks = ",".join(str(c) for c in G.PAL["loader"])
    bas = [
        "10 MODE 0:BORDER 0:FOR i=0 TO 15:READ c:INK i,c:NEXT",
        "20 MEMORY &3FFF",
        "30 LOAD\"SLOPSCR\",&C000",
        "40 OUT &7F00,&C4:LOAD\"BG1\",&4000",
        "50 OUT &7F00,&C5:LOAD\"BG2\",&4000",
        "60 OUT &7F00,&C6:LOAD\"BG3\",&4000",
        "70 OUT &7F00,&C7:LOAD\"GFX7\",&4000",
        "80 OUT &7F00,&C0:LOAD\"HIGH\",&4000:CALL &4000",
        "90 DATA " + inks,
    ]
    with open(os.path.join(BUILD, "loader.bas"), "w") as f:
        f.write("\r\n".join(bas) + "\r\n\x1a")
    print("loader: %s" % ("art" if real else "placeholder"))


def write(name, data, binary=False):
    with open(os.path.join(BUILD, name), "wb" if binary else "w") as f:
        f.write(data)


def main():
    os.makedirs(BUILD, exist_ok=True)
    G.selftest()
    build_tables()
    build_palettes()
    build_sprites()
    for ep in (1, 2, 3):
        real = build_background(ep)
        print("bg%d: %s" % (ep, "art" if real else "placeholder"))
    build_menu_and_c7()
    build_loader()


if __name__ == "__main__":
    main()
