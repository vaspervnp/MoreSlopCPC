# sprite sets: SS_PLAYER(5) SS_ROBOT(2) SS_ITEMS(6) SS_POWER(2) SS_POOF(3) SS_BOLT(1) SS_BRO(3)
SETS = {
    "spr_set_ep1": ["themis_m1"] * 5 + ["robot_m1"] * 2 + ["items_ep1"] * 6 + ["power_m1"] * 2
                   + ["poof_m1"] * 3 + ["bolt_m1"] + ["bro_float"] + ["bro_walk"] * 2,
}


def build_sprites():
    out = ["; generated by tools/build_assets.py - do not edit"]
    labels = {}
    used_art = []
    for name, (mode, pal, fw, fh, n) in SPRITES.items():
        img, real = art(name)
        if real:
            used_art.append(name)
        assert img.size == (fw * n, fh), (name, img.size, (fw * n, fh))
        palrgb = G.pal_rgb(pal)
        labels[name] = []
        for f in range(n):
            fr = img.crop((f * fw, 0, f * fw + fw, fh))
            data = G.sprite_bytes(fr, palrgb, mode)
            lab = "spr_%s_%d" % (name, f)
            labels[name].append(lab)
            out.append(lab + ":")
            out.append(G.db_lines(data))

    def set_table(lab, player, robot, items, power, poof, bolt):
        refs = labels[player] + labels[robot] + labels[items] + labels[power] + labels[poof] \
            + labels[bolt] + labels["bro_float"] + labels["bro_walk"]
        assert len(refs) == 22
        out.append(lab + ":")
        out.append("    dw " + ",".join(refs))

    set_table("spr_set_ep1", "themis_m1", "robot_m1", "items_ep1", "power_m1", "poof_m1", "bolt_m1")
    set_table("spr_set_ep2", "themis_m1", "robot_m1", "items_ep2", "power_m1", "poof_m1", "bolt_m1")
    set_table("spr_set_ep3", "themis_m0", "robot_m0", "items_ep3", "power_m0", "poof_m0", "bolt_m0")
    write("sprites.asm", "\n".join(out) + "\n")
    print("sprites: real art for %s" % (", ".join(used_art) or "nothing yet"))


# ---------------------------------------------------------------- tables
def build_tables():
    out = ["; generated by tools/build_assets.py - do not edit", "line_tab:"]
    offs = [G.line_offset(y) for y in range(200)]
    for i in range(0, 200, 10):
        out.append("    dw " + ",".join("#%04X" % o for o in offs[i:i + 10]))
    out.append("m0_left:")
    out.append("    db " + ",".join("#%02X" % G.m0_byte(p, 0) for p in range(16)))
    wheel = [6, 15, 24, 18, 20, 11, 2, 5, 8, 7]
    out.append("rainbow:")
    out.append("    db " + ",".join("#%02X" % G.ga_colour(c) for c in wheel))
    write("tables.asm", "\n".join(out) + "\n")


def zone(label, mode, pal, n=None):
    cols = G.PAL[pal] if isinstance(pal, str) else pal
    if n is not None:
        cols = cols[:n]
    m = {None: 0, 0: 0x8C, 1: 0x8D}[mode]
    return "%s: db #%02X,%d,%s" % (label, m, len(cols), ",".join("#%02X" % G.ga_colour(c) for c in cols))


def build_palettes():
    out = ["; generated by tools/build_assets.py - do not edit"]
    out.append("rast_black: dw 0,rz_black,0,0,0,0")
    out.append(zone("rz_black", None, [0] * 16))
    for ep in (1, 2):
        out.append("rast_ep%d: dw 0,rz_hud%d,rz_pf%d,0,0,rz_shelf%d" % (ep, ep, ep, ep))
        out.append(zone("rz_hud%d" % ep, 1, "hud%d" % ep))
        out.append(zone("rz_pf%d" % ep, 1, "ep%d" % ep))
        out.append(zone("rz_shelf%d" % ep, None, "shelf%d" % ep))
    out.append("rast_ep3: dw 0,rz_hud3,rz_pf3,0,0,0")
    out.append(zone("rz_hud3", 1, "hud3"))
    out.append(zone("rz_pf3", 0, "ep3"))
    out.append("rast_menu: dw 0,rz_menu1,rz_menu2,rz_menu3,rz_menu4,rz_menu5")
    out.append(zone("rz_menu1", 0, "menu"))
    for z in range(2, 6):
        out.append(zone("rz_menu%d" % z, None, "menu", 4))
    write("palettes.asm", "\n".join(out) + "\n")


# ---------------------------------------------------------- full screens
def pens_of(img, pal):
    """picture -> rows of pens (nearest colour of `pal`)."""
    pens, _ = G.image_pens(img.convert("RGBA"), G.pal_rgb(pal) if isinstance(pal, str) else pal,
                           alpha=False)
    return pens


def png(name):
    p = os.path.join(ART, name + ".png")
    return Image.open(p).convert("RGBA") if os.path.exists(p) else None


def hud_band():
    rows = [[0] * 320 for _ in range(32)]
    for x in range(320):
        rows[17][x] = 2
        rows[18][x] = 3
        rows[19][x] = 2
        if x % 4 != 3:
            rows[21][x] = 1
    return rows


def build_background(ep):
    """lines 0-31 HUD (Mode 1), 32-39 blank, 40-189 playfield (Mode 1, or
    Mode 0 for episode 3), 190-199 shelf."""
    pf = png("bg%d_pf" % ep)
    real = pf is not None
    blank = [[0] * 320 for _ in range(8)]
    if not real:
        ph = P.background(ep)
        pf = ph.crop((0, 40, 320, 190))
    if ep == 3:
        if pf.width == 320:
            pf = pf.resize((160, 150), Image.NEAREST)
        pfp = pens_of(pf, "ep3")
        sh = png("shelf_m0") or Image.new("RGB", (160, 10))
        shp = pens_of(sh, "ep3")
        bands = [(0, 32, 1, hud_band()), (32, 40, 1, blank), (40, 190, 0, pfp), (190, 200, 0, shp)]
    else:
        pfp = pens_of(pf, "ep%d" % ep)
        sh = png("shelf_m1") or Image.new("RGB", (320, 10))
        shp = pens_of(sh, "shelf1")
        bands = [(0, 32, 1, hud_band()), (32, 40, 1, blank), (40, 190, 1, pfp), (190, 200, 1, shp)]
    scr = G.screen_from_bands(bands)
    write("BG%d" % ep, scr, binary=True)
    preview(bands, "bg%d_preview.png" % ep, ep)
    return real


def logo_pens(img, pens, bgpen=0):
    """RGBA logo render -> rows of pens by brightness (dark, mid, light)."""
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        r = []
        for x in range(w):
            R, Gg, Bb, A = px[x, y]
            if A < 128:
                r.append(None)
                continue
            l = (R * 3 + Gg * 6 + Bb) / 10
            r.append(pens[2] if l > 200 else pens[1] if l > 110 else pens[0])
        rows.append(r)
    # dark outline around the letters
    out = [list(r) for r in rows]
    for y in range(h):
        for x in range(w):
            if rows[y][x] is None:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < w and 0 <= ny < h and rows[ny][nx] is not None:
                        out[y][x] = -1
                        break
    return out


def stars(w, h, pen, seed, n):
    import random
    rnd = random.Random(seed)
    rows = [[0] * w for _ in range(h)]
    for _ in range(n):
        rows[rnd.randrange(h)][rnd.randrange(w)] = pen
    return rows


def overlay(base, top, outline_pen):
    for y, r in enumerate(top):
        for x, p in enumerate(r):
            if p is None:
                continue
            base[y][x] = outline_pen if p == -1 else p


def rom_font():
    rom = open(os.path.expanduser("~/cpcemu/roms/cpc6128_os.bin"), "rb").read()
    return rom[0x3800:0x4000]


def m0_text(rows, x, y, s, pen):
    """Draw with the CPC ROM font onto 160-wide pen rows (8x8 per char)."""
    f = rom_font()
    for i, ch in enumerate(s):
        g = f[ord(ch) * 8:ord(ch) * 8 + 8]
        for r in range(8):
            for b in range(8):
                if g[r] & (0x80 >> b) and 0 <= x + i * 8 + b < 160:
                    rows[y + r][x + i * 8 + b] = pen


def menu_screen():
    rows = [[0] * 160 for _ in range(200)]
    sky = stars(160, 60, 13, 7, 40)
    for y in range(60):
        rows[y] = sky[y]
    lg = png("menu_logo")
    if lg:
        lg = lg.resize((160, 60), Image.NEAREST) if lg.width != 160 else lg
        top = logo_pens(lg, (1, 2, 3))
        for y in range(60):
            for x in range(160):
                p = top[y][x]
                if p is not None:
                    rows[y][x] = 4 if p == -1 else p
    sc = png("menu_scene")
    if sc:
        sp = pens_of(sc, "menu")
        for y in range(60):
            rows[60 + y] = sp[y]
    # the panel frame
    for x in range(4, 156):
        for y in (116, 187):
            rows[y][x] = 7
        for y in (117, 186):
            rows[y][x] = 10
    for y in range(116, 188):
        for x in (4, 155):
            rows[y][x] = 7
        for x in (5, 154):
            rows[y][x] = 10
    return rows, (lg is not None and sc is not None)


def loader_screen():
    rows = [[0] * 160 for _ in range(200)]
    sk = stars(160, 50, 14, 3, 30)
    for y in range(50):
        rows[y] = sk[y]
    sc = png("loader_scene")
    if sc:
        sp = pens_of(sc, "loader")
        for y in range(150):
            rows[50 + y] = sp[y]
    lg = png("loader_logo")
    if lg:
        top = logo_pens(lg, (6, 7, 8))
        overlay(rows, top, 0)
    for y in range(186, 200):
        rows[y] = [0] * 160
    m0_text(rows, 16, 189, "LOADING SLOP", 10)
    return rows, (sc is not None and lg is not None)


def preview(bands, name, ep):
    """What the CPC will show, as a PNG (for reviewing the art)."""
    pals = {}
    if ep == 3:
        pal_pf = G.pal_rgb("ep3")
        pal_shelf = G.pal_rgb("ep3")
    elif ep in (1, 2):
        pal_pf = G.pal_rgb("ep%d" % ep)
        pal_shelf = G.pal_rgb("shelf%d" % ep)
    else:
        pal_pf = pal_shelf = G.pal_rgb(ep)
    img = Image.new("RGB", (320, 200))
    for y0, y1, mode, rows in bands:
        if ep in (1, 2, 3):
            pal = G.pal_rgb("hud%d" % ep) if y0 == 0 else (pal_shelf if y0 == 190 else pal_pf)
        else:
            pal = pal_pf
        for y in range(y0, y1):
            r = rows[y - y0]
            sx = 320 // len(r)
            for x, p in enumerate(r):
                for k in range(sx):
                    img.putpixel((x * sx + k, y), pal[p])
    img.resize((640, 400), Image.NEAREST).save(os.path.join(BUILD, name))


def build_menu_and_c7():
    rows, real = menu_screen()
    bands = [(0, 200, 0, rows)]
    preview(bands, "menu_preview.png", "menu")
    scr = G.screen_from_bands(bands)
    packed = G.lz_pack(scr)
    assert G.lz_unpack(packed) == scr
    assert len(packed) <= 0x4000, len(packed)
    write("GFX7", packed, binary=True)
    write("c7.asm", "; generated - contents of bank #C7\nc7_menu equ #4000\n")
    print("menu: %d bytes packed (%s)" % (len(packed), "art" if real else "placeholder"))


def build_loader():
    rows, real = loader_screen()
    bands = [(0, 200, 0, rows)]
    preview(bands, "loader_preview.png", "loader")
    write("SLOPSCR", G.screen_from_bands(bands), binary=True)
    inks = ",".join(str(c) for c in G.PAL["loader"])
    bas = [
        "10 MODE 0:BORDER 0:FOR i=0 TO 15:READ c:INK i,c:NEXT",
        "20 MEMORY &3FFF",
        "30 LOAD\"SLOPSCR\",&C000",
        "40 OUT &7F00,&C4:LOAD\"BG1\",&4000",
        "50 OUT &7F00,&C5:LOAD\"BG2\",&4000",
        "60 OUT &7F00,&C6:LOAD\"BG3\",&4000",
        "70 OUT &7F00,&C7:LOAD\"GFX7\",&4000",
        "80 OUT &7F00,&C0:LOAD\"HIGH\",&4000:CALL &4000",
        "90 DATA " + inks,
    ]
    with open(os.path.join(BUILD, "loader.bas"), "w") as f:
        f.write("\r\n".join(bas) + "\r\n\x1a")
    print("loader: %s" % ("art" if real else "placeholder"))


def write(name, data, binary=False):
    with open(os.path.join(BUILD, name), "wb" if binary else "w") as f:
        f.write(data)


def main():
    os.makedirs(BUILD, exist_ok=True)
    G.selftest()
    build_tables()
    build_palettes()
    build_sprites()
    for ep in (1, 2, 3):
        real = build_background(ep)
        print("bg%d: %s" % (ep, "art" if real else "placeholder"))
    build_menu_and_c7()
    build_loader()


if __name__ == "__main__":
    main()
