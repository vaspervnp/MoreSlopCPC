"""Turn the art in art/png into everything the Z80 needs.

    python3 tools/build_assets.py

Writes into build/:
  tables.asm    line offsets, Mode 0 pen bits, rainbow
  palettes.asm  raster tables (palette + mode per interrupt zone)
  sprites.asm   the masked sprites every episode shares (HIGH)
  ep<n>_spr.asm the episode's item / obstacle / decoy sprites (HIGH blob)
  ep<n>_pal.asm the episode's raster zones (LOW blob)
  BG<n>         16K screen image of each episode's background
  MENU.SCR      16K menu picture (packed by tools/pack_banks.py)
  SLOPSCR       the loading screen (raw 16K, loaded at #C000)
  loader.bas    the BASIC loader (with the loading-screen inks)

A missing PNG falls back to a generated placeholder, so the game always
builds; tools/placeholders.py documents the expected sizes.
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import cpcgfx as G          # noqa: E402
import placeholders as P    # noqa: E402
import episodes as E        # noqa: E402

ART = os.path.join(ROOT, "art", "png")
BUILD = os.path.join(ROOT, "build")


def art(name, pal=None, fw=None, fh=None, n=None):
    p = os.path.join(ART, name + ".png")
    if os.path.exists(p):
        return Image.open(p).convert("RGBA"), True
    return P.make(name, pal, fw, fh, n), False


# ---------------------------------------------------------------- sprites
# shared by all episodes: name -> (mode, palette, frame width px, height, frames)
SPRITES = {
    "themis_m1": (1, "ep1", 24, 24, 5),
    "robot_m1":  (1, "ep1", 32, 20, 2),
    "power_m1":  (1, "ep1", 16, 16, 6),
    "poof_m1":   (1, "ep1", 16, 16, 3),
    "bolt_m1":   (1, "ep1", 8, 10, 1),
    "themis_m0": (0, "ep3", 12, 24, 5),
    "robot_m0":  (0, "ep3", 16, 20, 2),
    "power_m0":  (0, "ep3", 8, 16, 6),
    "poof_m0":   (0, "ep3", 8, 16, 3),
    "bolt_m0":   (0, "ep3", 4, 10, 1),
}
# obstacle characters (the "bros"): art name prefix -> mode
BROS = {"bro": 0, "guru": 1, "chef": 0, "evang": 1}


def ep_pal(e):
    return "ep%d" % e["n"]


def ep_sprites(e):
    """(art name, label stem, frame w, h, frames) for one episode."""
    n, mode = e["n"], e["mode"]
    iw = 16 if mode == 1 else 8
    out = [("items_ep%d" % n, "items", iw, 16, 6)]
    if e["bro"]:
        b = e["bro"]
        bw = 24 if BROS[b] == 1 else 12
        out += [("%s_float" % b, "bro_float", bw, 32, 1), ("%s_walk" % b, "bro_walk", bw, 24, 2)]
    if E.has_decoy(e):
        out.append(("decoy_ep%d" % n, "decoy", iw, 16, 2))
    return out


def encode_frames(name, mode, pal, fw, fh, n, prefix, out, used):
    img, real = art(name, pal, fw, fh, n)
    if real:
        used.append(name)
    assert img.size == (fw * n, fh), (name, img.size, (fw * n, fh))
    palrgb = G.pal_rgb(pal)
    for f in range(n):
        fr = img.crop((f * fw, 0, f * fw + fw, fh))
        out.append("%s_%d:" % (prefix, f))
        out.append(G.db_lines(G.sprite_bytes(fr, palrgb, mode)))


def build_sprites():
    out = ["; generated by tools/build_assets.py - do not edit"]
    used = []
    for name, (mode, pal, fw, fh, n) in SPRITES.items():
        encode_frames(name, mode, pal, fw, fh, n, "spr_" + name, out, used)
    write("sprites.asm", "\n".join(out) + "\n")
    for e in E.EPISODES:
        eo = ["; generated by tools/build_assets.py - do not edit"]
        for name, stem, fw, fh, n in ep_sprites(e):
            encode_frames(name, e["mode"], ep_pal(e), fw, fh, n, "e%d_%s" % (e["n"], stem), eo, used)
        write("ep%d_spr.asm" % e["n"], "\n".join(eo) + "\n")
    print("sprites: real art for %s" % (", ".join(sorted(set(used))) or "nothing yet"))


# ---------------------------------------------------------------- tables
def build_tables():
    out = ["; generated by tools/build_assets.py - do not edit", "line_tab:"]
    offs = [G.line_offset(y) for y in range(200)]
    for i in range(0, 200, 10):
        out.append("    dw " + ",".join("#%04X" % o for o in offs[i:i + 10]))
    out.append("m0_left:")
    out.append("    db " + ",".join("#%02X" % G.m0_byte(p, 0) for p in range(16)))
    wheel = [6, 15, 24, 18, 20, 11, 2, 5, 8, 7]
    out.append("rainbow:")
    out.append("    db " + ",".join("#%02X" % G.ga_colour(c) for c in wheel))
    write("tables.asm", "\n".join(out) + "\n")


def zone(label, mode, pal, n=None):
    cols = G.PAL[pal] if isinstance(pal, str) else pal
    if n is not None:
        cols = cols[:n]
    m = {None: 0, 0: 0x8C, 1: 0x8D}[mode]
    return "%s: db #%02X,%d,%s" % (label, m, len(cols), ",".join("#%02X" % G.ga_colour(c) for c in cols))


def build_palettes():
    out = ["; generated by tools/build_assets.py - do not edit"]
    out.append("rast_black: dw 0,rz_black,0,0,0,0")
    out.append(zone("rz_black", None, [0] * 16))
    out.append("rast_menu: dw 0,rz_menu1,rz_menu2,rz_menu3,rz_menu4,rz_menu5")
    out.append(zone("rz_menu1", 0, "menu"))
    for z in range(2, 6):
        out.append(zone("rz_menu%d" % z, None, "menu", 4))
    write("palettes.asm", "\n".join(out) + "\n")
    for e in E.EPISODES:
        n = e["n"]
        eo = ["; generated by tools/build_assets.py - do not edit"]
        eo.append(zone("e%d_rz_hud" % n, 1, "hud%d" % n))
        eo.append(zone("e%d_rz_pf" % n, e["mode"], ep_pal(e)))
        if e["mode"] == 1:
            eo.append(zone("e%d_rz_shelf" % n, None, "shelf%d" % n))
        write("ep%d_pal.asm" % n, "\n".join(eo) + "\n")


# ---------------------------------------------------------- full screens
def pens_of(img, pal):
    """picture -> rows of pens (nearest colour of `pal`)."""
    pens, _ = G.image_pens(img.convert("RGBA"), G.pal_rgb(pal) if isinstance(pal, str) else pal,
                           alpha=False)
    return pens


def png(name):
    p = os.path.join(ART, name + ".png")
    return Image.open(p).convert("RGBA") if os.path.exists(p) else None


def hud_band():
    rows = [[0] * 320 for _ in range(32)]
    for x in range(320):
        rows[17][x] = 2
        rows[18][x] = 3
        rows[19][x] = 2
        if x % 4 != 3:
            rows[21][x] = 1
    return rows


def build_background(e):
    """lines 0-31 HUD (Mode 1), 32-39 blank, 40-189 playfield (the episode's
    mode), 190-199 shelf."""
    n, mode, pal = e["n"], e["mode"], ep_pal(e)
    pf = png("bg%d_pf" % n)
    real = pf is not None
    if not real:
        pf = P.background(n, mode, pal)
    blank = [[0] * 320 for _ in range(8)]
    if mode == 0:
        if pf.width == 320:
            pf = pf.resize((160, 150), Image.NEAREST)
        pfp = pens_of(pf, pal)
        sh = png("shelf_m0") or Image.new("RGB", (160, 10))
        shp = pens_of(sh, pal)
    else:
        pfp = pens_of(pf, pal)
        sh = png("shelf_m1") or Image.new("RGB", (320, 10))
        shp = pens_of(sh, "shelf%d" % n)
    bands = [(0, 32, 1, hud_band()), (32, 40, 1, blank), (40, 190, mode, pfp), (190, 200, mode, shp)]
    write("BG%d" % n, G.screen_from_bands(bands), binary=True)
    preview(bands, "bg%d_preview.png" % n, e)
    return real


def logo_pens(img, pens, bgpen=0):
    """RGBA logo render -> rows of pens by brightness (dark, mid, light)."""
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        r = []
        for x in range(w):
            R, Gg, Bb, A = px[x, y]
            if A < 128:
                r.append(None)
                continue
            l = (R * 3 + Gg * 6 + Bb) / 10
            r.append(pens[2] if l > 200 else pens[1] if l > 110 else pens[0])
        rows.append(r)
    # dark outline around the letters
    out = [list(r) for r in rows]
    for y in range(h):
        for x in range(w):
            if rows[y][x] is None:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < w and 0 <= ny < h and rows[ny][nx] is not None:
                        out[y][x] = -1
                        break
    return out


def stars(w, h, pen, seed, n):
    import random
    rnd = random.Random(seed)
    rows = [[0] * w for _ in range(h)]
    for _ in range(n):
        rows[rnd.randrange(h)][rnd.randrange(w)] = pen
    return rows


def overlay(base, top, outline_pen):
    for y, r in enumerate(top):
        for x, p in enumerate(r):
            if p is None:
                continue
            base[y][x] = outline_pen if p == -1 else p


def rom_font():
    rom = open(os.path.expanduser("~/cpcemu/roms/cpc6128_os.bin"), "rb").read()
    return rom[0x3800:0x4000]


def m0_text(rows, x, y, s, pen):
    """Draw with the CPC ROM font onto 160-wide pen rows (8x8 per char)."""
    f = rom_font()
    for i, ch in enumerate(s):
        g = f[ord(ch) * 8:ord(ch) * 8 + 8]
        for r in range(8):
            for b in range(8):
                if g[r] & (0x80 >> b) and 0 <= x + i * 8 + b < 160:
                    rows[y + r][x + i * 8 + b] = pen


def menu_screen():
    rows = [[0] * 160 for _ in range(200)]
    sky = stars(160, 60, 13, 7, 40)
    for y in range(60):
        rows[y] = sky[y]
    lg = png("menu_logo")
    if lg:
        lg = lg.resize((160, 60), Image.NEAREST) if lg.width != 160 else lg
        top = logo_pens(lg, (1, 2, 3))
        for y in range(60):
            for x in range(160):
                p = top[y][x]
                if p is not None:
                    rows[y][x] = 4 if p == -1 else p
    sc = png("menu_scene")
    if sc:
        sp = pens_of(sc, "menu")
        for y in range(60):
            rows[60 + y] = sp[y]
    # the panel frame
    for x in range(4, 156):
        for y in (116, 187):
            rows[y][x] = 7
        for y in (117, 186):
            rows[y][x] = 10
    for y in range(116, 188):
        for x in (4, 155):
            rows[y][x] = 7
        for x in (5, 154):
            rows[y][x] = 10
    return rows, (lg is not None and sc is not None)


def loader_screen():
    rows = [[0] * 160 for _ in range(200)]
    sk = stars(160, 50, 14, 3, 30)
    for y in range(50):
        rows[y] = sk[y]
    sc = png("loader_scene")
    if sc:
        sp = pens_of(sc, "loader")
        for y in range(150):
            rows[50 + y] = sp[y]
    lg = png("loader_logo")
    if lg:
        top = logo_pens(lg, (6, 7, 8))
        overlay(rows, top, 0)
    for y in range(186, 200):
        rows[y] = [0] * 160
    m0_text(rows, 16, 189, "LOADING SLOP", 10)
    return rows, (sc is not None and lg is not None)


def preview(bands, name, e):
    """What the CPC will show, as a PNG (for reviewing the art)."""
    img = Image.new("RGB", (320, 200))
    for y0, y1, mode, rows in bands:
        if isinstance(e, str):
            pal = G.pal_rgb(e)
        elif y0 == 0:
            pal = G.pal_rgb("hud%d" % e["n"])
        elif y0 == 190 and e["mode"] == 1:
            pal = G.pal_rgb("shelf%d" % e["n"])
        else:
            pal = G.pal_rgb(ep_pal(e))
        for y in range(y0, y1):
            r = rows[y - y0]
            sx = 320 // len(r)
            for x, p in enumerate(r):
                for k in range(sx):
                    img.putpixel((x * sx + k, y), pal[p])
    img.resize((640, 400), Image.NEAREST).save(os.path.join(BUILD, name))


def build_menu():
    rows, real = menu_screen()
    bands = [(0, 200, 0, rows)]
    preview(bands, "menu_preview.png", "menu")
    write("MENU.SCR", G.screen_from_bands(bands), binary=True)
    print("menu: %s" % ("art" if real else "placeholder"))


def build_loader():
    rows, real = loader_screen()
    bands = [(0, 200, 0, rows)]
    preview(bands, "loader_preview.png", "loader")
    write("SLOPSCR", G.screen_from_bands(bands), binary=True)
    inks = ",".join(str(c) for c in G.PAL["loader"])
    bas = [
        "10 MODE 0:BORDER 0:FOR i=0 TO 15:READ c:INK i,c:NEXT",
        "20 MEMORY &3FFF",
        "30 LOAD\"SLOPSCR\",&C000",
        "40 OUT &7F00,&C5:LOAD\"BANK5\",&4000",
        "50 OUT &7F00,&C6:LOAD\"BANK6\",&4000",
        "60 OUT &7F00,&C7:LOAD\"BANK7\",&4000",
        "80 OUT &7F00,&C0:LOAD\"HIGH\",&4000:CALL &4000",
        "90 DATA " + inks,
    ]
    with open(os.path.join(BUILD, "loader.bas"), "w") as f:
        f.write("\r\n".join(bas) + "\r\n\x1a")
    print("loader: %s" % ("art" if real else "placeholder"))


def write(name, data, binary=False):
    with open(os.path.join(BUILD, name), "wb" if binary else "w") as f:
        f.write(data)


def main():
    os.makedirs(BUILD, exist_ok=True)
    G.selftest()
    build_tables()
    build_palettes()
    build_sprites()
    for e in E.EPISODES:
        real = build_background(e)
        print("bg%d: %s" % (e["n"], "art" if real else "placeholder"))
    build_menu()
    build_loader()


if __name__ == "__main__":
    main()
