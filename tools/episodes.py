"""The ten episodes of MORE SLOP: structure shared by all the generators.

Each episode becomes two blobs, assembled by rasm in their own memory spaces
(see build/episodes.asm, written here) and packed into the extra banks by
tools/pack_banks.py:
  HIGH blob at EP_HI:  header (sprite set, card, message tables), item and
                       obstacle sprites, texts
  LOW  blob at lo_slot: raster table, mode, obstacles, mechanics, the song
At the start of an episode both are unpacked into place (src/episode.asm).
"""
import os
import sys

# obstacles (bit mask)
POP, BAN, BRO = 1, 2, 4
# mechanics (bit mask)
DECOY_REV = 1    # a falling deepfake of Themis: zapping it flips the controls
DECOY_MISS = 2   # a falling human: zapping it counts as slop on the shelf
SPLIT = 4        # zapped slop may split in two
BEAT = 8         # every so often the bass drops and everything falls faster
BOSS = 16        # wave 3 ends with a fight against the SlopBot itself

EPISODES = [
    dict(n=1, mode=1, title=("THE HALLUCINATION", "FACTORY"), obst=POP, mech=0, bro=None),
    dict(n=2, mode=1, title=("THE CLICKBAIT", "EXPRESS"), obst=BAN, mech=0, bro=None),
    dict(n=3, mode=0, title=("THE CRYPTO", "GRAVEYARD"), obst=BRO, mech=0, bro="bro"),
    dict(n=4, mode=1, title=("THE DEEPFAKE", "STUDIO"), obst=POP, mech=DECOY_REV, bro=None),
    dict(n=5, mode=1, title=("THE SEO CONTENT", "FARM"), obst=BAN, mech=SPLIT, bro=None),
    dict(n=6, mode=0, title=("THE CHATBOT", "HELPLINE"), obst=POP, mech=DECOY_MISS, bro=None),
    dict(n=7, mode=1, title=("THE THOUGHT", "LEADER SUMMIT"), obst=BRO, mech=0, bro="guru"),
    dict(n=8, mode=0, title=("THE AI", "KITCHEN"), obst=BRO, mech=SPLIT, bro="chef"),
    dict(n=9, mode=0, title=("THE SLOP-FI", "FESTIVAL"), obst=POP, mech=BEAT, bro=None),
    dict(n=10, mode=1, title=("THE SLOP", "SINGULARITY"), obst=POP | BAN | BRO, mech=BOSS, bro="evang"),
]
for _e in EPISODES:
    assert not (_e["mode"] == 0 and _e["obst"] & BAN), "banners are Mode 1 only"
    assert bool(_e["obst"] & BRO) == bool(_e["bro"])

# header of the HIGH blob (offsets, must match src/const.asm EH_*)
EH_FIELDS = ["card", "popt", "poptitle", "heads", "kill", "miss", "popin", "popdone",
             "banin", "bandone", "broin", "brohit", "broleft", "brodone", "decoy",
             "special", "boss"]
SET_ENTRIES = 24          # sprite set: player 5, robot 2, items 6, power 2, poof 3,
                          # bolt 1, bro float 1, bro walk 2, decoy 2


def has_decoy(e):
    return bool(e["mech"] & (DECOY_REV | DECOY_MISS))


def build(path):
    const = ["; generated by tools/episodes.py - do not edit"]
    for i, f in enumerate(EH_FIELDS):
        const.append("EH_%s equ %d" % (f.upper(), SET_ENTRIES * 2 + 2 * i))
    const.append("EH_SIZE equ %d" % (SET_ENTRIES * 2 + 2 * len(EH_FIELDS)))
    const.append("NUM_EPS equ %d" % len(EPISODES))
    for k in ("POP", "BAN", "BRO", "DECOY_REV", "DECOY_MISS", "SPLIT", "BEAT", "BOSS"):
        const.append("%s_%s equ %d" % ("OB" if k in ("POP", "BAN", "BRO") else "MC", k, globals()[k]))
    with open(os.path.join(os.path.dirname(path), "ep_const.asm"), "w") as f:
        f.write("\n".join(const) + "\n")
    out = ["; generated by tools/episodes.py - do not edit", ""]
    for e in EPISODES:
        n = e["n"]
        p = "e%d_" % n
        m = "m%d" % e["mode"]
        bro = e["bro"]
        set_refs = (["spr_themis_%s_%d" % (m, i) for i in range(5)]
                    + ["spr_robot_%s_%d" % (m, i) for i in range(2)]
                    + ["%sitems_%d" % (p, i) for i in range(6)]
                    + ["spr_power_%s_%d" % (m, i) for i in range(2)]
                    + ["spr_poof_%s_%d" % (m, i) for i in range(3)]
                    + ["spr_bolt_%s_0" % m]
                    + (["%sbro_float_0" % p, "%sbro_walk_0" % p, "%sbro_walk_1" % p] if bro
                       else ["%sitems_0" % p] * 3)
                    + (["%sdecoy_0" % p, "%sdecoy_1" % p] if has_decoy(e) else ["%sitems_0" % p] * 2))
        assert len(set_refs) == SET_ENTRIES
        out += ["", "; ---- episode %d: %s %s" % (n, *e["title"]),
                "    bank", "    org EP_HI", "%shi:" % p,
                "    dw " + ",".join(set_refs[:12]),
                "    dw " + ",".join(set_refs[12:]),
                "    dw " + ",".join("%s%s" % (p, f) for f in EH_FIELDS),
                '    include "ep%d_spr.asm"' % n,
                '    include "ep%d_txt.asm"' % n,
                "%shi_end:" % p,
                "    assert %shi_end <= #8000" % p,
                '    print "EP%d HI ",{hex4}%shi_end-EP_HI' % (n, p),
                '    save "build/EP%dHI.BIN",EP_HI,%shi_end-EP_HI' % (n, p),
                "    bank", "    org lo_slot", "%slo:" % p,
                "    dw 0,%srz_hud,%srz_pf,0,0,%s" % (p, p, ("%srz_shelf" % p) if e["mode"] else "0"),
                "    db %d,%d,%d,0" % (e["mode"], e["obst"], e["mech"]),
                '    include "ep%d_song.asm"' % n,
                '    include "ep%d_pal.asm"' % n,
                "%slo_end:" % p,
                "    assert %slo_end-lo_slot <= LO_SLOT_SIZE" % p,
                '    print "EP%d LO ",{hex4}%slo_end-lo_slot' % (n, p),
                '    save "build/EP%dLO.BIN",lo_slot,%slo_end-lo_slot' % (n, p)]
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else os.path.join("build", "episodes.asm"))
